class ShareTab extends StatefulWidget {
  final TextEditingController codeCtrl;
  const ShareTab({super.key, required this.codeCtrl});

  @override
  State<ShareTab> createState() => _ShareTabState();
}

class _ShareTabState extends State<ShareTab> {
  final _phoneCtrl = TextEditingController();
  StreamSubscription<Position>? _sub;
  bool _sharing = false;
  String _status = 'Sharing band hai.';

  @override
  void initState() {
    super.initState();
    SharedPreferences.getInstance().then((p) {
      _phoneCtrl.text = p.getString('my_phone') ?? '';
      setState(() {});
    });
  }

  Future<bool> _ensurePermission() async {
    if (!await Geolocator.isLocationServiceEnabled()) {
      setState(() => _status = 'Phone ka Location (GPS) ON karo.');
      return false;
    }
    var perm = await Geolocator.checkPermission();
    if (perm == LocationPermission.denied) {
      perm = await Geolocator.requestPermission();
    }
    if (perm == LocationPermission.denied ||
        perm == LocationPermission.deniedForever) {
      setState(() => _status = 'Location permission nahi mili.');
      return false;
    }
    return true;
  }

  Future<void> _start() async {
    final phone = normalizePhone(_phoneCtrl.text);
    final code = widget.codeCtrl.text.trim();
    if (phone.length != 10 || code.isEmpty) {
      setState(() => _status = 'Family code aur 10 digit phone number daalo.');
      return;
    }
    if (!await _ensurePermission()) return;

    final p = await SharedPreferences.getInstance();
    await p.setString('my_phone', phone);

    final LocationSettings settings = Platform.isAndroid
        ? AndroidSettings(
            accuracy: LocationAccuracy.high,
            distanceFilter: 20,
            intervalDuration: const Duration(seconds: 30),
            // Visible notification = user always knows sharing is ON.
            foregroundNotificationConfig: const ForegroundNotificationConfig(
              notificationTitle: 'Family Locator',
              notificationText: 'Aapki location family ke saath share ho rahi hai',
              enableWakeLock: true,
            ),
          )
        : AppleSettings(
            accuracy: LocationAccuracy.high,
            distanceFilter: 20,
            activityType: ActivityType.other,
            pauseLocationUpdatesAutomatically: true,
            showBackgroundLocationIndicator: true,
            allowBackgroundLocationUpdates: true,
          );

    _sub = Geolocator.getPositionStream(locationSettings: settings).listen(
      (pos) async {
        try {
          await memberDoc(code, phone).set({
            'lat': pos.latitude,
            'lng': pos.longitude,
            'accuracy': pos.accuracy,
            'updatedAt': FieldValue.serverTimestamp(),
          });
          if (mounted) {
            setState(() => _status =
                'Sharing ON: ${pos.latitude.toStringAsFixed(5)}, ${pos.longitude.toStringAsFixed(5)}');
          }
        } catch (e) {
          if (mounted) setState(() => _status = 'Upload error: $e');
        }
      },
      onError: (e) => setState(() => _status = 'GPS error: $e'),
    );
    setState(() {
      _sharing = true;
      _status = 'Sharing shuru ho raha hai...';
    });
  }

  Future<void> _stop() async {
    await _sub?.cancel();
    _sub = null;
    setState(() {
      _sharing = false;
      _status = 'Sharing band hai.';
    });
  }

  @override
  void dispose() {
    _sub?.cancel();
    _phoneCtrl.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        TextField(
          controller: _phoneCtrl,
          enabled: !_sharing,
          keyboardType: TextInputType.phone,
          decoration: const InputDecoration(
            labelText: 'Mera phone number',
            border: OutlineInputBorder(),
          ),
        ),
        const SizedBox(height: 16),
        FilledButton.icon(
          onPressed: _sharing ? _stop : _start,
          icon: Icon(_sharing ? Icons.stop : Icons.play_arrow),
          label: Text(_sharing ? 'Stop sharing' : 'Start sharing'),
        ),
        const SizedBox(height: 16),
        Text(_status),
        const SizedBox(height: 8),
        const Text(
          'Sharing tabhi hoti hai jab aap Start dabate ho. '
          'Kabhi bhi Stop daba kar band kar sakte ho.',
          style: TextStyle(color: Colors.grey),
        ),
      ],
    );
  }
}

