Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  if (FirebaseAuth.instance.currentUser == null) {
    await FirebaseAuth.instance.signInAnonymously();
  }
  runApp(const FamilyLocatorApp());
}

class FamilyLocatorApp extends StatelessWidget {
  const FamilyLocatorApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Family Locator',
      debugShowCheckedModeBanner: false,
      theme: ThemeData(colorSchemeSeed: Colors.teal, useMaterial3: true),
      home: const HomeScreen(),
    );
  }
}

/// Keep only the last 10 digits so "+91 98765-43210" and "9876543210" match.
String normalizePhone(String input) {
  final digits = input.replaceAll(RegExp(r'\D'), '');
  return digits.length > 10 ? digits.substring(digits.length - 10) : digits;
}

DocumentReference<Map<String, dynamic>> memberDoc(String code, String phone) =>
    FirebaseFirestore.instance
        .collection('families')
        .doc(code.trim())
        .collection('members')
        .doc(phone);

class HomeScreen extends StatefulWidget {
  const HomeScreen({super.key});

  @override
  State<HomeScreen> createState() => _HomeScreenState();
}

class _HomeScreenState extends State<HomeScreen> {
  final _codeCtrl = TextEditingController();
  int _tab = 0;

  @override
  void initState() {
    super.initState();
    SharedPreferences.getInstance().then((p) {
      _codeCtrl.text = p.getString('family_code') ?? '';
      setState(() {});
    });
  }

  Future<void> _saveCode() async {
    final p = await SharedPreferences.getInstance();
    await p.setString('family_code', _codeCtrl.text.trim());
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('Family Locator')),
      body: Padding(
        padding: const EdgeInsets.all(16),
        child: Column(
          children: [
            TextField(
              controller: _codeCtrl,
              onChanged: (_) => _saveCode(),
              decoration: const InputDecoration(
                labelText: 'Family code (sab members ka same)',
                helperText: 'Ek secret code rakho, sirf family ko batao',
                border: OutlineInputBorder(),
              ),
            ),
            const SizedBox(height: 16),
            SegmentedButton<int>(
              segments: const [
                ButtonSegment(
                    value: 0,
                    icon: Icon(Icons.search),
                    label: Text('Find member')),
                ButtonSegment(
                    value: 1,
                    icon: Icon(Icons.share_location),
                    label: Text('Share mine')),
              ],
              selected: {_tab},
              onSelectionChanged: (s) => setState(() => _tab = s.first),
            ),
            const SizedBox(height: 16),
            Expanded(
              child: _tab == 0
                  ? FindTab(codeCtrl: _codeCtrl)
                  : ShareTab(codeCtrl: _codeCtrl),
            ),
          ],
        ),
      ),
    );
  }
}

