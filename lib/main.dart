class FindTab extends StatefulWidget {
  final TextEditingController codeCtrl;
  const FindTab({super.key, required this.codeCtrl});

  @override
  State<FindTab> createState() => _FindTabState();
}

class _FindTabState extends State<FindTab> {
  final _phoneCtrl = TextEditingController();
  bool _loading = false;
  String? _error;
  double? _lat, _lng;
  DateTime? _updatedAt;

  Future<void> _fetch() async {
    final phone = normalizePhone(_phoneCtrl.text);
    final code = widget.codeCtrl.text.trim();
    if (phone.length != 10 || code.isEmpty) {
      setState(() => _error = 'Family code aur 10 digit phone number daalo.');
      return;
    }
    setState(() {
      _loading = true;
      _error = null;
    });
    try {
      final snap = await memberDoc(code, phone).get();
      if (!snap.exists) {
        setState(() {
          _error = 'Is number ki location nahi mili.';
          _lat = _lng = null;
        });
      } else {
        final d = snap.data()!;
        setState(() {
          _lat = (d['lat'] as num).toDouble();
          _lng = (d['lng'] as num).toDouble();
          _updatedAt = (d['updatedAt'] as Timestamp?)?.toDate();
        });
      }
    } catch (e) {
      setState(() => _error = 'Error: $e');
    } finally {
      setState(() => _loading = false);
    }
  }

  /// Opens the official Google Maps app. No SDK / API key involved.
  Future<void> _openMaps() async {
    final lat = _lat!, lng = _lng!;
    final candidates = <Uri>[
      if (Platform.isAndroid)
        // Android Intent: explicitly handled by Google Maps
        Uri.parse('geo:$lat,$lng?q=$lat,$lng(Family%20Member)'),
      if (Platform.isIOS)
        // iOS URL scheme of the Google Maps app
        Uri.parse('comgooglemaps://?q=$lat,$lng&center=$lat,$lng&zoom=16'),
      // Universal fallback (opens Maps app if installed, else browser)
      Uri.parse(
          'https://www.google.com/maps/search/?api=1&query=$lat,$lng'),
    ];
    for (final uri in candidates) {
      try {
        if (await launchUrl(uri, mode: LaunchMode.externalApplication)) return;
      } catch (_) {}
    }
    if (mounted) {
      ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text('Google Maps nahi khul paya.')));
    }
  }

  @override
  void dispose() {
    _phoneCtrl.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        TextField(
          controller: _phoneCtrl,
          keyboardType: TextInputType.phone,
          decoration: const InputDecoration(
            labelText: 'Family member ka phone number',
            border: OutlineInputBorder(),
          ),
        ),
        const SizedBox(height: 16),
        FilledButton.icon(
          onPressed: _loading ? null : _fetch,
          icon: const Icon(Icons.my_location),
          label: Text(_loading ? 'Fetching...' : 'Fetch latest location'),
        ),
        const SizedBox(height: 16),
        if (_error != null)
          Text(_error!, style: const TextStyle(color: Colors.red)),
        if (_lat != null) ...[
          Text('Lat: $_lat\nLng: $_lng'),
          if (_updatedAt != null) Text('Last update: $_updatedAt'),
          const SizedBox(height: 12),
          FilledButton.tonalIcon(
            onPressed: _openMaps,
            icon: const Icon(Icons.map),
            label: const Text('Open in Google Maps'),
          ),
        ],
      ],
    );
  }
}
